# -----------------------------------------------------------------------------

def test_router_primary_success(db_session: Session, sample_context):
    """Verify primary provider succeeds and logs single invocation with fallback_triggered=False."""
    p1 = AlwaysSuccessMockProvider("openai")
    p2 = AlwaysSuccessMockProvider("gemini")
    p3 = DeterministicFallbackProvider()

    router = LLMRouter(providers=[p1, p2, p3])
    diag = router.diagnose_case(context=sample_context, db=db_session, case_id="case_1")

    assert diag.recommended_strategy == "PAYMENT_LINK"

    invocations = db_session.query(LLMInvocation).filter_by(recovery_case_id="case_1").all()
    assert len(invocations) == 1
    assert invocations[0].provider == "openai"
    assert invocations[0].success is True
    assert invocations[0].fallback_triggered is False

def test_router_single_fallback(db_session: Session, sample_context):
    """Verify primary fails -> secondary succeeds and logs both invocations."""
    p1 = AlwaysFailingMockProvider("openai")
    p2 = AlwaysSuccessMockProvider("gemini", strategy="RETRY")
    p3 = DeterministicFallbackProvider()

    router = LLMRouter(providers=[p1, p2, p3])
    diag = router.diagnose_case(context=sample_context, db=db_session, case_id="case_2")

    assert diag.recommended_strategy == "RETRY"

    invocations = db_session.query(LLMInvocation).filter_by(recovery_case_id="case_2").all()
    assert len(invocations) == 2

    # OpenAI attempt (failed)
    assert invocations[0].provider == "openai"
    assert invocations[0].success is False
    assert invocations[0].fallback_triggered is True

    # Gemini attempt (succeeded)
    assert invocations[1].provider == "gemini"
    assert invocations[1].success is True
    assert invocations[1].fallback_triggered is True

def test_router_double_fallback_to_deterministic(db_session: Session, sample_context):
    """Verify primary & secondary fail -> deterministic succeeds."""
    p1 = AlwaysFailingMockProvider("openai")
    p2 = AlwaysFailingMockProvider("gemini")
    p3 = DeterministicFallbackProvider()

    router = LLMRouter(providers=[p1, p2, p3])
    diag = router.diagnose_case(context=sample_context, db=db_session, case_id="case_3")

    assert diag.recommended_strategy == "PAYMENT_LINK"

    invocations = db_session.query(LLMInvocation).filter_by(recovery_case_id="case_3").all()
    assert len(invocations) == 3

    assert invocations[0].provider == "openai" and invocations[0].success is False
    assert invocations[1].provider == "gemini" and invocations[1].success is False
    assert invocations[2].provider == "deterministic" and invocations[2].success is True
    assert invocations[2].fallback_triggered is True

