def test_prompt_no_hidden_ground_truth_leakage(sample_context):
    prompt = build_user_prompt(sample_context)
    prompt_lower = prompt.lower()

    forbidden_terms = [
        "simulation_ground_truth",
        "true_recovery_probability",
        "simulated_outcome",
        "future_outcome",
    ]
    for term in forbidden_terms:
        assert term not in prompt_lower, f"Forbidden leakage term '{term}' found in user prompt!"
