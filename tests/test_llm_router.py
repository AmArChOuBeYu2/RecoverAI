# Mock Provider implementations for controlled testing
class AlwaysSuccessMockProvider(LLMProvider):
    def __init__(self, provider_name: str, strategy: str = "PAYMENT_LINK"):
        self._name = provider_name
        self._strategy = strategy

    @property
    def name(self) -> str:
        return self._name

    @property
    def model_name(self) -> str:
        return f"{self._name}-mock-v1"

    def diagnose(self, context: Dict[str, Any]) -> Tuple[RecoveryDiagnosis, Dict[str, Any]]:
        diag = RecoveryDiagnosis(
            failure_category="AUTHENTICATION_FAILURE",
            diagnosis=f"Diagnosis generated by {self._name}",
            recoverability_score=0.8,
            confidence=0.9,
            recommended_strategy=self._strategy,
            reasoning_summary=f"Reasoning by {self._name}",
        )
        metadata = {"latency_ms": 150, "prompt_tokens": 100, "completion_tokens": 50}
        return diag, metadata

class AlwaysFailingMockProvider(LLMProvider):
    def __init__(self, provider_name: str):
        self._name = provider_name

    @property
    def name(self) -> str:
        return self._name

    @property
    def model_name(self) -> str:
        return f"{self._name}-fail-v1"

    def diagnose(self, context: Dict[str, Any]) -> Tuple[RecoveryDiagnosis, Dict[str, Any]]:
        raise LLMProviderError(self._name, f"Mock failure in {self._name}")

